/** One sub-cover inside a hub product. `href` promotes it to its own page. */
export type ProductVariant = {
  title: string;
  blurb: string;
  href?: string;
};

/** Sub-covers sharing a common source of risk, e.g. "ευθύνη από τη λειτουργία". */
export type VariantGroup = {
  label: string;
  items: ProductVariant[];
};

/** A cover that belongs to a neighbouring product, not this one. */
export type RelatedCover = {
  title: string;
  href: string;
  note: string;
};

export type Product = {
  icon: LucideIcon;
  title: string;
  slug: string;
  color: string; // revealed on hover when the grayscale filter lifts
  image: string; // hero photo, lives in /public/products/
  imagePosition?: string; // object-position for the hero photo (default "center")
  intro: string; // short hero paragraph (blue panel)
  description: string; // opening body paragraph
  covers: string[]; // "Τι καλύπτει" list
  needs: string[]; // "Τι θα χρειαστείτε" sidebar checklist — what the client should have ready for a quote
  // Kept out of the navbar dropdown, but still reachable at its own URL and
  // still listed on /asfaleies. Set from the CMS "Κρυφό από το μενού"
  // checkbox; the EXTRA_*_PAGES arrays below are marked hidden in
  // cmsProducts.ts, which is what has always kept them out of the navbar.
  hidden?: boolean;
  // Hub products only: the sub-covers this category splits into, grouped by
  // where the risk comes from. Rendered as tiles above "Τι καλύπτει".
  variantsHeading?: string;
  variantGroups?: VariantGroup[];
  // Covers a client would look for here but that live in another product —
  // keeps category boundaries explicit instead of implied.
  relatedHeading?: string;
  related?: RelatedCover[];
};

