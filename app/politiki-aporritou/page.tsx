// The copy carries a couple of bare URLs (Google's policy, the DPA). Rendering
// them as anchors keeps the SECTIONS entries plain strings, as on /oroi-xrisis.
// Split keeps the capture group, so the URLs come back as their own entries.
// The test uses a separate, non-global regex — /g carries lastIndex between
// calls and would match every other URL only.
const URL_PATTERN = /(https?:\/\/[^\s)\]]+)/g;
const IS_URL = /^https?:\/\//;

function withLinks(text: string) {
  return text.split(URL_PATTERN).map((part, i) =>
    IS_URL.test(part) ? (
      <a
        key={i}
        href={part}
        target="_blank"
        rel="noopener noreferrer"
        style={{ color: "#a30000", textDecoration: "underline" }}
      >
        {part}
      </a>
    ) : (
      part
    )
  );
}

